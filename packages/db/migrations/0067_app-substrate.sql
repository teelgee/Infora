-- ── `app_rows` — three CHECKs, and they are the record's integrity ──────────
--
-- A DECIDED ROW NAMES ITS DECIDER AND ITS TIME, AND NOTHING ELSE DOES.
-- Acceptance is the moment a row changes hands (ADR-0056 §2a): until then it is
-- the submitting organisation's own material, and on acceptance it becomes the
-- project owner's record. An act with nobody's name on it is not an audit
-- record — and a decider recorded on a row nobody has decided is a claim the
-- table would be making falsely. `state IN (...)` is NULL when `state` is NULL,
-- so a row on a table with no acceptance step takes the ELSE branch, which is
-- the correct answer for it.
-- `superseded` is the one state that may go either way, and the carve-out is
-- argued rather than convenient: a superseded row that was ACCEPTED still has
-- to name the person who accepted it, because that decision happened and the
-- correction does not unhappen it — while a superseded DRAFT was never decided
-- by anybody and must not claim to have been. Requiring null there would erase
-- the very attribution this constraint exists to keep. (The drawing said
-- "null otherwise"; this is that, narrowed by one state, recorded here.)
ALTER TABLE "app_rows" ADD CONSTRAINT "app_rows_decided_pair"
  CHECK (
    CASE
      WHEN "state" IN ('accepted', 'rejected')
        THEN "decided_by_participant_id" IS NOT NULL AND "decided_at" IS NOT NULL
      WHEN "state" = 'superseded'
        THEN num_nonnulls("decided_by_participant_id", "decided_at") IN (0, 2)
      ELSE "decided_by_participant_id" IS NULL AND "decided_at" IS NULL
    END
  );--> statement-breakpoint

-- A REJECTION CARRIES A REASON, AND ONLY A REJECTION CARRIES ONE (the
-- 2026-09-06 addendum, ruling 4, reversing the drawing's earlier "no reason on
-- a rejection"). The review record's precedent is that every comment gets a
-- response; a rejection with no reason becomes a phone call, which is the
-- record failing. It is a database rule and not only a route's validation
-- because a route can be bypassed by the next route somebody writes.
ALTER TABLE "app_rows" ADD CONSTRAINT "app_rows_rejection_reason_iff_rejected"
  CHECK (
    CASE WHEN "state" = 'rejected'
         THEN "rejection_reason" IS NOT NULL
         ELSE "rejection_reason" IS NULL
    END
  );--> statement-breakpoint

