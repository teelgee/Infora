-- T-370 — the agent act, and its receipt (ADR-0027's S10 amendment,
-- owner-ruled 2026-08-09).
--
-- The amendment licenses an embedded agent to execute ADMINISTRATIVE work
-- directly — folder structures, schema setup, plan housekeeping — within the
-- invoker's own permissions, on two conditions: the act is audited as
-- AGENT-PERFORMED, and there is a visible "what the agent did" receipt with
-- undo. **Nothing may adopt that lane until both substrates exist**, and this
-- table is both, which is why it holds the receipt's state beside the
-- attribution.
--
-- A SIDE TABLE, NOT AN `acting_run_id` COLUMN ON EACH AUDITED ACT. The subject
-- row's existing attribution stays CORRECT — the agent acts within the
-- invoker's own permissions, so the participant really is who the act is
-- attributable to. Agent performance is an ADDITIONAL fact about the same act,
-- and a column would read as replacing the attribution rather than adding to
-- it. `subject_id` is deliberately not a foreign key, for Drawer 8's reason: a
-- per-kind column is a schema change every new act kind would need.
--
-- `act` IS TEXT AND ITS VOCABULARY IS EMPTY ON PURPOSE. Nothing performs an
-- administrative act yet, so a closed enum would be T-301's rule broken twice
-- over: values the schema carries that no code can set. The first adopting
-- ticket adds one act kind and one undo handler.
--
-- NO `undone_by_participant_id` and NO `undoable`. The receipt belongs to the
-- run, the run already names its requester, and only that requester may undo —
-- so the actor is fixed by construction and this table introduces no new
-- named-person data. Whether an act can STILL be undone is a runtime question
-- (an added folder that now holds documents is additive and no longer safely
-- removable), so it is the handler's answer at the moment of asking.
--
-- Generated by drizzle-kit; the trigger and the grant at the foot are
-- hand-added, as every trigger in this repo is.
CREATE TABLE "agent_acts" (
	"id" uuid PRIMARY KEY DEFAULT gen_random_uuid() NOT NULL,
	"run_id" uuid NOT NULL,
	"act" text NOT NULL,
	"subject_kind" text NOT NULL,
	"subject_id" uuid NOT NULL,
	"summary" text NOT NULL,
	"performed_at" timestamp with time zone DEFAULT now() NOT NULL,
	"undone_at" timestamp with time zone
);
