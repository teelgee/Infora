-- T-332 — the audited use of the promotion override (ADR-0049 §7/§8).
--
-- Promotion is BLOCKED by open comment threads or open findings (§7,
-- owner-ruled against the recommendation to warn): nothing reaches the
-- controlled library with loose ends, and the two lists are treated identically
-- so the surface never has to explain why one stops you and the other does not.
--
-- §8 adds the only lawful way past, because a block with no escape is a
-- DEADLOCK rather than a stricter gate: a finding against a paragraph a later
-- redraft deleted, or a thread whose author has left the project, would
-- otherwise prevent promotion permanently. The override is
-- `Participant.elevated` only — the tier ruled 2026-07-31, reused rather than a
-- bypass invented for this — and every use lands in this table.
--
-- NOT `elevated_refusals`, which is its near-twin: that table records an act
-- REFUSED for want of the tier and this one records an act PERFORMED with it.
-- One table for both would need a column meaning "did this happen", which is
-- two records wearing one shape.
--
-- THE COUNTS ARE STORED RATHER THAN RECOMPUTED, for `purge_events`' reason one
-- store along: afterwards there is nothing to count. Threads get closed and
-- findings get cleared in the ordinary course of the work, so a record that
-- recomputed them would report zero — answering "somebody pressed the button"
-- instead of "somebody pressed the button past four open threads".
--
-- Its twin is 0058, which adds `promote_over_open_items` to `elevated_action`:
-- the refusal path and the success path are one gate, and this ticket writes
-- both. Two files rather than one because drizzle-kit emits an enum widening
-- separately, and hand-merging two generated snapshots to save a number is
-- exactly the kind of edit T-344 spent a ticket recovering from.
--
-- Generated by drizzle-kit; the trigger and the grant at the foot are
-- hand-added, as every trigger in this repo is.
