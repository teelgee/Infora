-- Append-only (T-008's trigger), with the undo state as the one carve-out — the
-- same two-phase shape `notifications` takes (migration 0056), and for the same
-- reason: what the act SAYS is evidence and only its undo state moves. An audit
-- of agent behaviour that the agent's invoker could rewrite is worth nothing.
CREATE OR REPLACE FUNCTION agent_acts_immutable_content() RETURNS trigger AS $$
BEGIN
	IF TG_OP = 'DELETE' THEN
		RAISE EXCEPTION 'agent act % is evidence: DELETE rejected', OLD.id;
	END IF;
	IF NEW.id IS DISTINCT FROM OLD.id
		 OR NEW.run_id IS DISTINCT FROM OLD.run_id
		 OR NEW.act IS DISTINCT FROM OLD.act
		 OR NEW.subject_kind IS DISTINCT FROM OLD.subject_kind
		 OR NEW.subject_id IS DISTINCT FROM OLD.subject_id
		 OR NEW.summary IS DISTINCT FROM OLD.summary
		 OR NEW.performed_at IS DISTINCT FROM OLD.performed_at
	THEN
		RAISE EXCEPTION 'agent act % is immutable: only undone_at may change', OLD.id;
	END IF;
	RETURN NEW;
END;
$$ LANGUAGE plpgsql;--> statement-breakpoint

CREATE TRIGGER agent_acts_immutable_content
	BEFORE UPDATE OR DELETE ON agent_acts
	FOR EACH ROW EXECUTE FUNCTION agent_acts_immutable_content();--> statement-breakpoint

