-- T-397 — the PROJECT STYLE GUIDE: project context, and the first material the
-- guiding channel has ever actually carried (ADR-0053 §3).
--
-- In plain terms: a project can now have its own writing rules — the owner's
-- house style for the scheme — and every organisation working on the project is
-- held to them. Stored clause by clause, like a firm's own manual, so a check
-- can quote "§4.2" rather than "page 11".
--
-- THE ONLY SCOPE KEY IS THE PROJECT, and there is deliberately no
-- `organisation_id`. ADR-0021 classifies context by OWNERSHIP: a firm's
-- drafting manual is the firm's own IP and leaves when the firm leaves, so it
-- is org context; a project style guide belongs to the project and binds
-- everyone on it. An owning-organisation column would make this a firm's manual
-- wearing a project's name, and the wall would then have two answers to "who
-- may read this clause" — which is precisely what makes a quoted style-guide
-- clause NOT org-private where a quoted rulebook clause is (ADR-0053 §9).
--
-- The shape is `rulebooks`' one store along, and nothing in it is copied for
-- tidiness: the nullable clause label, the verbatim text, the span and the
-- `retired_at` currency-by-state each have the same reason here they had there,
-- and two style sources stored differently would need two readers.
--
-- ONE MIGRATION FOR BOTH HALVES OF T-397. The other half — the rulebook moving
-- from the *guiding* channel to the *informing* one, per ADR-0048's dated
-- addendum — changes no schema at all: it is a code label and its tests. Same
-- table, same `organisation_id` key, no wall predicate added and none removed.
--
-- Drawn in docs/build/data-model.md before it was written; generated by
-- drizzle-kit against the current snapshot and read before being applied. The
-- CHECK and the GRANT at the foot are hand-added, as every one in this repo is.
