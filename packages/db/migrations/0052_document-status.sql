-- T-383 — record state and the grounding rule (the document-status session:
-- ADR-0013 as amended, with ADR-0003, ADR-0041, ADR-0045 and the ADR-0011
-- rider). Drawn in docs/build/data-model.md before it was written.
--
-- Small, and deliberately so: the state machine already existed. `container_state`
-- needs NO change — `live` · `superseded` · `withdrawn` · `rejected` were all
-- present from the start, and nothing ever set `superseded`. What changes is
-- who may write those states and what reads them.
--
-- ⚠ The drawing and T-383's own title say "migration 0048". That number was
-- already taken by T-305's `0048_pdf-document-format`; this is 0052, the next
-- free number, and the drawing's label is corrected in the same commit.
--
-- 1. `acceptance_codes` gains `is_contractual` and `grounds` (ADR-0003 as
--    amended). Library membership was one condition for grounding; it is now
--    three — in the library, AND record state `live`, AND admitted by a code
--    the project marks as grounding (the ADR-0011 rider).
-- 2. `containers` gains `withdrawn_by_participant_id` (ADR-0013 §5). Only the
--    free-text reason was stored, so nothing recorded WHICH SIDE withdrew and
--    restoration could not tell its own act from the other party's. A named
--    person on a destructive act, registered in
--    docs/architecture/personal-data.md.
--
-- Nothing is stored for context state, deliberately: it is derived from library
-- membership + record state + the code's `grounds` flag in the same SQL
-- pre-filter retrieval already runs. Storing it would be a second state machine
-- that could disagree with the first, invisibly — every citation would still
-- resolve (ADR-0013 §6).
--
