-- T-390 — the acceptance-code change record (ADR-0003 as amended 2026-08-27,
-- ADR-0030). Drawn in docs/build/data-model.md before it was written.
--
-- WHY A TABLE AT ALL. The scheme editor's writes are not preferences: turning a
-- code's `grounds` flag off changes what the AI may rely on across a whole
-- project, and it does it SILENTLY — every citation that already exists still
-- resolves, so nothing about the system looks different afterwards. ADR-0003
-- therefore requires the change to be audited like a rails change. There is no
-- rails-change machinery to reuse (rails as scoped records is still undrawn),
-- and every audit in this repo is a purpose-built append-only table, so this is
-- one more of those.
--
-- One property per row, with its old and new value, and the reason in free
-- text. A code's history reads as a sequence of DECISIONS rather than of states,
-- and the reason is the half a diff cannot reconstruct.
--
-- Generated by drizzle-kit; the append-only trigger at the foot is hand-added,
-- as every trigger in this repo is. New tables pick up the `infora_app` grants
-- from migration 0034's ALTER DEFAULT PRIVILEGES, as 0049-0051 did.
