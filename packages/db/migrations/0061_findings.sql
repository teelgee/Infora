-- T-310 -- THE CHECKER'S FINDINGS: the store the promotion gate has been
-- counting through a hole.
--
-- In plain terms: when someone runs the QA checker over a draft, each problem
-- it finds is one row here -- what is wrong, where in the draft it is, what
-- evidence it rests on, and whether anybody has dealt with it yet. Until this
-- migration there was no table at all, so the rule that an unresolved finding
-- stops a draft being promoted was a rule about an empty list.
--
-- DRAWER 4 AND NOT DRAWER 2, which is the near-miss worth naming: a finding
-- resolves like a sandbox comment and is counted beside one by ADR-0049
-- section 7, but it is PRODUCED BY A RUN, it may carry a Suggestion as its
-- proposed fix, and clearing it is a human resolution of an agent's output --
-- which is drawer 4's whole subject.
--
-- MUTABLE, like the sandbox it annotates, for the sandbox comment's reason
-- exactly: an append-only finding would need a second table to say it had been
-- cleared. Everything append-only about the run that produced it -- what it
-- spent, what it saw -- is already on the Step row.
--
-- PER RUN OF ONE DOCUMENT, AND NOTHING ACROSS RUNS. There is no column, index
-- or key here relating one run's findings to the previous run's. That is
-- deliberate: whether findings persist across runs of the same document, so a
-- dismissal is remembered and a re-raised finding recognised, is ADR-0048's own
-- open lifecycle question, given a driver by ADR-0053 section 13 and left
-- unruled. A carry-over built now would be answering it in schema.
--
-- THE THREE STEP TYPES are the checker's three capabilities, and three because
-- the grain is the capability boundary (ADR-0053 section 2): the per-section
-- families take one section, self-contradiction is one call over the section
-- summaries, and readability and completeness are CODE over the whole document.
-- Nothing in this migration USES a new enum value, so the ALTER TYPE runs in
-- the transaction safely (migration 0055's precedent).
--
-- Drawn in docs/build/data-model.md before it was written; generated by
-- drizzle-kit against the current snapshot and read before being applied. The
-- GRANT at the foot is hand-added, as every one in this repo is.
