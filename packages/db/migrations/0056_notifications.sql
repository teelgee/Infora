-- IMMUTABLE EVENT, MUTABLE READ STATE — the T-008 pattern applied to a
-- two-phase row, exactly as `plans` does it. A notification is evidence that
-- somebody was told, so what it SAYS is frozen at insert and only the read
-- state moves. Without this the recipient, the event or the subject could be
-- rewritten after the fact, and "who was told what, when" would be an assertion
-- rather than a property.
--
-- DELETE is left alone, and that is a deliberate non-decision: whether a
-- notification ever expires or is deleted rides with `Q-015`'s retention theme
-- (ADR-0049's own "Open" section says so). A trigger forbidding DELETE would be
-- ruling that question on the way past.
CREATE OR REPLACE FUNCTION notifications_immutable_content() RETURNS trigger AS $$
BEGIN
	IF NEW.id IS DISTINCT FROM OLD.id
		 OR NEW.recipient_participant_id IS DISTINCT FROM OLD.recipient_participant_id
		 OR NEW.event_type IS DISTINCT FROM OLD.event_type
		 OR NEW.subject_kind IS DISTINCT FROM OLD.subject_kind
		 OR NEW.subject_id IS DISTINCT FROM OLD.subject_id
		 OR NEW.created_at IS DISTINCT FROM OLD.created_at
	THEN
		RAISE EXCEPTION 'notification % is immutable: only read_at may change', OLD.id;
	END IF;
	RETURN NEW;
END;
$$ LANGUAGE plpgsql;--> statement-breakpoint

CREATE TRIGGER notifications_immutable_content
	BEFORE UPDATE ON notifications
	FOR EACH ROW EXECUTE FUNCTION notifications_immutable_content();--> statement-breakpoint

-- T-247's discipline: the application role reads and writes this like any other
-- table. The default privileges from 0034 cover tables created after it, but
-- state the grant rather than rely on it being remembered.
GRANT SELECT, INSERT, UPDATE, DELETE ON "notifications" TO "infora_app";
