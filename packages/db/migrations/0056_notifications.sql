-- T-329 — Drawer 8, the notification record (ADR-0049).
--
-- An event-shaped row: recipient, event type, a pointer to the subject, a
-- creation time and a read state. The record is the primary artefact and the
-- in-app list is the surface of record; email (T-330) is a nudge toward it.
--
-- THE MIGRATION NOTE ADR-0049 §2 ASKS FOR, because the ticket names it as an
-- acceptance criterion: **adding a third event type must not require a schema
-- change.** That is why `event_type` and `subject_kind` are `text` and not
-- Postgres enums — `ALTER TYPE ... ADD VALUE` is a migration, so an enum would
-- break the guard by construction. Seeding the deferred `lock-flipped` value
-- now would break the other rule instead, the one T-301 wrote down when it left
-- `supersede` out of `elevated_action`: a value the schema carries and no code
-- can set is a claim the schema makes falsely. The vocabulary therefore lives
-- in `packages/contracts` as a union every surface is typed against, and this
-- store holds the text. `lock-flipped` joins as a new event type over an
-- EXISTING subject kind (`sandbox_document`), so it needs neither this file nor
-- a new visibility resolver.
--
-- `subject_id` IS DELIBERATELY NOT A FOREIGN KEY for the same reason: it is
-- polymorphic across four tables in three drawers, and a per-kind FK column is
-- exactly the schema change the guard rules out. What that gives up is bought
-- back on the read path rather than lost — a subject that no longer resolves is
-- a notification visible to nobody, which is what a cascade would have produced
-- and what ADR-0049 §3's visibility rule demands regardless.
--
-- THE ROW STORES NO CONTENT. Visibility follows the subject, resolved through
-- the same path as the subject itself, so a notification is never a channel by
-- which a fact reaches someone who could not otherwise reach it (§3, ADR-0018).
-- A stored title or summary would sit OUTSIDE that path and still be readable
-- after the share that permitted it was revoked.
--
-- Generated by drizzle-kit on the T-344 re-synced snapshot; the trigger and the
-- grant at the foot are hand-added, as every trigger in this repo is.
CREATE TABLE "notifications" (
	"id" uuid PRIMARY KEY DEFAULT gen_random_uuid() NOT NULL,
	"recipient_participant_id" uuid NOT NULL,
	"event_type" text NOT NULL,
	"subject_kind" text NOT NULL,
	"subject_id" uuid NOT NULL,
	"created_at" timestamp with time zone DEFAULT now() NOT NULL,
	"read_at" timestamp with time zone
);
