-- the four document types reference material needs, into every existing
-- project's scheme where missing (by code or by label, live terms only). Data
-- rather than DDL, carried here so the two cannot drift from the seed.
INSERT INTO "classification_terms" ("facet_id", "code", "label", "sort_order")
SELECT f."id", v."code", v."label",
       COALESCE((SELECT MAX(t."sort_order") FROM "classification_terms" t WHERE t."facet_id" = f."id"), -1) + v."ord"
FROM "classification_facets" f
CROSS JOIN (VALUES
  ('STD', 'Standard', 1),
  ('GDN', 'Guidance', 2),
  ('LEG', 'Legislation', 3),
  ('CRS', 'Consultee response', 4)
) AS v("code", "label", "ord")
WHERE f."key" = 'document_type'
  AND NOT EXISTS (
    SELECT 1 FROM "classification_terms" t
    WHERE t."facet_id" = f."id"
      AND t."retired_at" IS NULL
      AND (t."code" = v."code" OR lower(t."label") = lower(v."label"))
  );
