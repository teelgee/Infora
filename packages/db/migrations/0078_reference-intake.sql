-- `not_citable` is set at insert and at no other time. The versions trigger
-- freezes its columns BY NAME (0013, 0049), so a column added later is
-- mutable until it is named — and this one decides whether a document can ever
-- be read by a run. The function is 0049's, verbatim, with the one condition added.
CREATE OR REPLACE FUNCTION versions_immutable_content() RETURNS trigger AS $$
BEGIN
  IF TG_OP = 'DELETE' THEN
    IF coalesce(current_setting('infora.purge', true), '') = 'on' THEN
      RETURN OLD;
    END IF;
    RAISE EXCEPTION 'versions are append-only: DELETE rejected';
  END IF;
  IF NEW.id IS DISTINCT FROM OLD.id
     OR NEW.container_id IS DISTINCT FROM OLD.container_id
     OR NEW.version_reference IS DISTINCT FROM OLD.version_reference
     OR NEW.content IS DISTINCT FROM OLD.content
     OR NEW.created_at IS DISTINCT FROM OLD.created_at
     OR NEW.not_citable IS DISTINCT FROM OLD.not_citable
  THEN
    RAISE EXCEPTION 'version % is append-only: only is_current may change', OLD.id;
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;
