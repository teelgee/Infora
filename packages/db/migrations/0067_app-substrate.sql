-- ── A PLAYBOOK CARRIES NO ROWS, OF ANY ORIGIN (ADR-0056 §10) ────────────────
--
-- The owner's veto-pass clarification, 2026-09-06: *"by reference tables i meant
-- the database structure for an app — not the content from within it."* So
-- "structure" includes a reference table's DEFINITION — its name, its columns,
-- its kind — and a deployed instance starts every table empty. The rule is
-- mechanical rather than a convention because the failure it prevents is a
-- firm's template walking out of one client's project carrying that client's
-- data into the next one, and a convention is exactly what would be forgotten
-- on the day a save path is rewritten.
--
-- A key named `rows` ANYWHERE in either JSON column is refused. Refusing the
-- key rather than sniffing for data is the honest guard: it is decidable, it is
-- explainable to the person who hits it, and it cannot be argued with.
CREATE OR REPLACE FUNCTION app_json_has_key(doc jsonb, needle text) RETURNS boolean AS $$
DECLARE
  key text;
  item jsonb;
BEGIN
  IF doc IS NULL THEN
    RETURN false;
  ELSIF jsonb_typeof(doc) = 'object' THEN
    FOR key IN SELECT jsonb_object_keys(doc) LOOP
      IF key = needle THEN RETURN true; END IF;
      IF app_json_has_key(doc -> key, needle) THEN RETURN true; END IF;
    END LOOP;
  ELSIF jsonb_typeof(doc) = 'array' THEN
    FOR item IN SELECT * FROM jsonb_array_elements(doc) LOOP
      IF app_json_has_key(item, needle) THEN RETURN true; END IF;
    END LOOP;
  END IF;
  RETURN false;
END;
$$ LANGUAGE plpgsql IMMUTABLE;--> statement-breakpoint

CREATE OR REPLACE FUNCTION playbooks_carry_no_rows() RETURNS trigger AS $$
BEGIN
  IF app_json_has_key(NEW.definition, 'rows') OR app_json_has_key(NEW.table_declarations, 'rows') THEN
    RAISE EXCEPTION 'a playbook carries structure and never rows (ADR-0056 §10): the definition names a `rows` key';
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;--> statement-breakpoint

CREATE TRIGGER playbooks_carry_no_rows
  BEFORE INSERT OR UPDATE ON playbooks
  FOR EACH ROW EXECUTE FUNCTION playbooks_carry_no_rows();--> statement-breakpoint

