export const DOCUMENT_CREATION_WORKFLOW = 'document-creation';

const notFound = (c: Context) => c.json({ error: 'not_found' } satisfies ApiError, 404);
const invalid = (c: Context, detail: string) =>
  c.json({ error: 'invalid', detail } satisfies ApiError, 400);
const isUuid = (value: string) => z.uuid().safeParse(value).success;

/**
 * T-414 — what a firm outline says about itself on the menu.
 *
 * **Computed, never typed and never generated by a model.** The description's
 * job here is to let a colleague choose between two outlines, and what settles
 * that is its size and whose judgement it is — both facts the record already
 * holds. Asking the saver to write a description would be asking for a second
 * label; asking a model would be an uncited claim about somebody's work.
 */
function describeFirmOutline(sections: DocumentSection[], savedByName: string): string {
  const parts = flattenOutline(sections).length;
  return `${parts} section${parts === 1 ? '' : 's'}, saved by ${savedByName}.`;
}

async function sandboxReachable(db: Db, slice: EntitledSlice, sandboxId: string): Promise<boolean> {
  const [sandbox] = await db.select().from(s.sandboxes).where(eq(s.sandboxes.id, sandboxId)).limit(1);
  if (!sandbox || sandbox.projectId !== slice.projectId) return false;
  const grants = await db
    .select()
    .from(s.sandboxScopeGrants)
    .where(
      and(eq(s.sandboxScopeGrants.sandboxId, sandboxId), isNull(s.sandboxScopeGrants.removedAt)),
    );
  return canAccessSandbox(
    slice,
    grants.map((g) => ({
      granteeType: g.granteeType,
      organisationId: g.organisationId,
      participantId: g.participantId,
      removedAt: g.removedAt,
    })),
  );
}

export function documentCreationRoutes(deps: {
  db: Db;
  leaves: ChainLeaves;
  templates: TemplateRegistry;
  /** T-409 — the agent pane's one model call, on the `draft` task class */
  router: Router;
  workflows?: WorkflowRegistry;
  capabilities?: CapabilityRegistry;
  workers?: WorkerRegistry;
  authorityShelf?: (organisationId: Id) => Promise<boolean>;
  modelRates?: ModelRates;
  /** the model id the drafting call would be routed to, for the estimate */
  draftModelId?: string;
}) {
  const app = new Hono<AppEnv>();
  const project = projectScope(deps);

  /**
   * The one planner both endpoints call. Returns the plan, or the reason the
   * request cannot produce one at all — which is a different thing from the
   * plan's own `refusal` (that one is a real plan saying "do not press this").
   */
  const plan = async (
    c: Context<AppEnv>,
  ): Promise<{ ok: true; plan: ToolPlan; body: ReturnType<typeof documentCreationBody.parse> } | { ok: false; response: Response }> => {
    const parsed = documentCreationBody.safeParse(await c.req.json().catch(() => null));
    if (!parsed.success) {
      return {
        ok: false,
        response: invalid(
          c,
          'sections (at least one, each with a heading and a purpose), brief, purpose, language, documentType, styleGuideIds, sourceVersionIds, destinationSandboxId, title',
        ),
      };
    }
    const workflow = deps.workflows?.get(DOCUMENT_CREATION_WORKFLOW);
    if (workflow === undefined) {
      return { ok: false, response: notFound(c) }; // this deployment carries no creator
    }
    // the destination is checked here, before the plan is priced: writing
    // somewhere you cannot reach is not a plan with a refusal on it, it is a
    // request about a sandbox that, to this requester, does not exist
    if (!(await sandboxReachable(deps.db, c.get('slice'), parsed.data.destinationSandboxId))) {
      return { ok: false, response: notFound(c) };
    }

    return {
      ok: true,
      body: parsed.data,
      plan: planDocumentCreation({
        workflow,
        // T-407 — the outline the AUTHOR composed. There is no template lookup
        // here any more and no "no such template" refusal: a starting outline
        // is a menu the surface fills, and by the time a request arrives the
        // sections in it are the author's own.
        sections: parsed.data.sections,
        brief: parsed.data.brief,
        sourceCount: parsed.data.sourceVersionIds.length,
        // T-406 — the four answers reach the planner, because the plan has to
        // SAY what it is about to write and under which resolution
        purpose: parsed.data.purpose,
        language: parsed.data.language,
        documentType: parsed.data.documentType,
        styleGuideCount: parsed.data.styleGuideIds.length,
        draftModelId: deps.draftModelId ?? 'unpriced',
        ...(deps.modelRates !== undefined && { rates: deps.modelRates }),
        tokenLimit: TOKEN_LIMIT,
      }),
    };
  };

  /**
   * T-407 — the starting outlines this deployment carries.
   *
   * *In plain terms: the two shipped templates, offered as a way to begin
   * rather than a shape to fit into.* Choosing one gives the author a list of
   * sections whose purposes are the template's own per-part guidance — all of
   * them editable, reorderable and removable, and starting from nothing is
   * equally valid. **The outline the run draws its shape from is the author's
   * list**, sent in the request body; nothing here is binding, which is the
   * whole difference between a starting outline and the "shape" A1 retired.
   *
   * Project-scoped like every other tool route so the entitlement check runs;
   * the content itself is the deployment's, not the project's.
   */
  /**
   * T-414 (ADR-0053 addendum A5) — the outlines this ORGANISATION saved.
   *
   * 🔒 **`organisation_id` IS THE ONLY SCOPE KEY, AND THE ORGANISATION COMES
   * OFF THE RESOLVED SLICE.** How a firm structures its documents is firm
   * know-how (ADR-0020, the rulebook's own scoping), so another organisation
   * on the same project never sees one of these rows — not greyed, not
   * summarised, absent. The `projectId` in the route is there for the
   * entitlement check and touches this query nowhere.
   *
   * **Retired outlines are not returned at all.** Currency by state means the
   * row survives so nothing that referenced it breaks; it does not mean the
   * menu keeps offering it.
   */
  const firmOutlines = async (
    organisationId: string,
    mayRetire: boolean,
  ): Promise<ListStartingOutlinesResponse['items']> => {
    const rows = await deps.db
      .select({
        id: s.startingOutlines.id,
        label: s.startingOutlines.label,
        sections: s.startingOutlines.sections,
        savedAt: s.startingOutlines.savedAt,
        savedByName: s.users.name,
      })
      .from(s.startingOutlines)
      .innerJoin(s.users, eq(s.users.id, s.startingOutlines.savedByUserId))
      .where(
        and(
          eq(s.startingOutlines.organisationId, organisationId),
          isNull(s.startingOutlines.retiredAt),
        ),
      )
      .orderBy(desc(s.startingOutlines.savedAt));
    return rows.map((row) => ({
      id: row.id,
      label: row.label,
      // computed rather than stored: the description's job on this menu is to
      // say what choosing it does, and for a firm outline that is its size and
      // its provenance — neither of which anybody should have to type
      description: describeFirmOutline(row.sections as DocumentSection[], row.savedByName),
      sections: row.sections as DocumentSection[],
      origin: 'firm' as const,
      savedBy: { name: row.savedByName },
      savedAt: row.savedAt.toISOString(),
      // 🔒 assembled, not filtered, at a button: the control is ABSENT for
      // someone who may not retire, never rendered and disabled
      ...(mayRetire && { mayRetire: true }),
    }));
  };

  /**
   * Whether this requester may retire one of their firm's outlines.
   *
   * **The rulebook's tier, and for the rulebook's reason** (T-308): this is the
   * firm's own material, curated at account level, so the gate is
   * `orgRole === 'admin'` and there is no project seat to check it against.
   * A5 is explicit that **anyone in the firm saves** — only retiring is the
   * curator's, which is the light-touch answer to a half-baked outline sitting
   * beside a shipped one looking authoritative.
   */
  const mayCurateOutlines = (c: Context<AppEnv>) => c.get('user').orgRole === 'admin';

  app.get(
    '/projects/:projectId/tools/document-creation/starting-outlines',
    project,
    async (c) =>
      c.json({
        items: [
          ...deps.templates.list().map((template) => ({
            id: template.id,
            label: template.label,
            description: template.description,
            sections: template.sections.map((section) => ({
              heading: section.heading,
              // the template's per-part guidance BECOMES the section's purpose
              // — the same words, now the author's to edit (A1)
              purpose: section.guidance,
            })),
            origin: 'infora' as const,
          })),
          // the firm's own, AFTER the shipped ones and marked as the firm's:
          // A5 requires the difference to be visible, because an outline
          // somebody saved last Tuesday and one Infora ships carry different
          // authority
          ...(await firmOutlines(c.get('slice').organisationId, mayCurateOutlines(c))),
        ],
      } satisfies ListStartingOutlinesResponse),
  );

  /**
   * T-414 — keep the outline you just built.
   *
   * **Anyone in the firm may** (A5), so there is no tier check here and adding
   * one would be re-ruling the addendum. The organisation and the person both
   * come off the resolved session, never off the body: contracts principle 3,
   * and the reason a "who saved it" field would have been a way to write
   * somebody else's name onto a record.
   */
  app.post(
    '/projects/:projectId/tools/document-creation/starting-outlines',
    project,
    async (c) => {
      const parsed = saveStartingOutlineBody.safeParse(await c.req.json().catch(() => null));
      if (!parsed.success) {
        return invalid(c, 'label, and sections (at least one, each with a heading and a purpose)');
      }
      const [row] = await deps.db
        .insert(s.startingOutlines)
        .values({
          organisationId: c.get('slice').organisationId,
          label: parsed.data.label.trim(),
          sections: parsed.data.sections,
          savedByUserId: c.get('user').id,
        })
        .returning();
      const saved = (await firmOutlines(c.get('slice').organisationId, mayCurateOutlines(c))).find(
        (outline) => outline.id === row!.id,
      );
      return c.json(saved!, 201);
    },
  );

  /**
   * T-414 — a curator retires one, and it stops being offered.
   *
   * 🔒 **RETIRE, NEVER DELETE** — currency by state, the rulebook's rule one
   * store along. And **the organisation ceiling is checked in the update's own
   * WHERE**, not before it, so another firm's outline and a nonexistent one
   * answer identically: principle 4, and the org wall at the same time.
   */
  app.delete(
    '/projects/:projectId/tools/document-creation/starting-outlines/:outlineId',
    project,
    async (c) => {
      const outlineId = c.req.param('outlineId');
      if (!mayCurateOutlines(c) || !isUuid(outlineId)) return notFound(c);
      const retired = await deps.db
        .update(s.startingOutlines)
        .set({ retiredAt: new Date() })
        .where(
          and(
            eq(s.startingOutlines.id, outlineId),
            eq(s.startingOutlines.organisationId, c.get('slice').organisationId),
            isNull(s.startingOutlines.retiredAt),
          ),
        )
        .returning();
      if (retired.length === 0) return notFound(c);
      return c.json({ ok: true });
    },
  );

  /**
   * T-409 (ADR-0053 addendum A2, second half) — revise ONE section's
   * description by saying what is wrong with it.
   *
   * 🔒 **ENTITLEMENT-CHECKED LIKE THE TOOL IT BELONGS TO.** A requester whose
   * assembled set carries no `document_builder` cannot reach the creator at
   * all, and its agent pane must answer identically — **absent, not refused**
   * (principle 4, the assembled-not-filtered rule). A pane that 403'd would
   * tell someone a tool exists that they were never shown.
   *
   * **It proposes; it does not apply.** The revised text goes back to the
   * surface, which sets it as `section.brief` and asks for a new plan through
   * the same path a typed correction takes. Nothing here writes, nothing here
   * runs, and no step list is touched by anything but the planner.
   */
  app.post(
    '/projects/:projectId/tools/document-creation/section-brief/revision',
    project,
    async (c) => {
      const slice = c.get('slice');
      const entitled =
        deps.workers?.assemble({
          slice,
          tier: 'standard',
          authorityShelf: (await deps.authorityShelf?.(slice.organisationId)) ?? false,
        }) ?? [];
      if (
        deps.workflows?.get(DOCUMENT_CREATION_WORKFLOW) === undefined ||
        !entitled.some((worker) => worker.name === 'document_builder')
      ) {
        return notFound(c);
      }
      const parsed = reviseSectionBriefBody.safeParse(await c.req.json().catch(() => null));
      if (!parsed.success) return invalid(c, 'heading, purpose, brief and ask');
      const revision = await reviseSectionBrief(deps.router, parsed.data);
      return c.json(revision satisfies ReviseSectionBriefResult);
    },
  );

  app.post('/projects/:projectId/tools/document-creation/plan', project, async (c) => {
    const computed = await plan(c);
    if (!computed.ok) return computed.response;
    return c.json({ plan: computed.plan } satisfies DocumentCreationPlanResponse);
  });

  app.post('/projects/:projectId/tools/document-creation/runs', project, async (c) => {
    const computed = await plan(c);
    if (!computed.ok) return computed.response;
    // ADR-0053 §5 — the refusal is said in the plan, BEFORE any spend, and the
    // run endpoint honours it rather than treating it as advice. A caveat under
    // an empty document is read after the disappointment.
    if (computed.plan.refusal !== null) return invalid(c, computed.plan.refusal);

    const slice = c.get('slice');
    const workflow = deps.workflows!.get(DOCUMENT_CREATION_WORKFLOW)!;
    let bound;
    try {
      bound = bindWorkflow(workflow, {
        // T-407 — as JSON, which is the shape `families` takes in the
        // checker's own definition: the declared parameter types carry no "list
        // of objects", and widening that fixed set is an owner decision rather
        // than a build one. `sectionsOf` in the capability registry parses it
        // back and drops anything malformed, exactly as `familiesOf` does.
        sections: JSON.stringify(computed.body.sections),
        brief: computed.body.brief,
        purpose: computed.body.purpose,
        language: computed.body.language,
        document_type: computed.body.documentType,
        style_guide_ids: computed.body.styleGuideIds,
        sources: computed.body.sourceVersionIds,
        destination_sandbox_id: computed.body.destinationSandboxId,
        title: computed.body.title,
        // 🔒 T-427 (ADR-0054 decision 7) — which version of the accepted
        // writing rules this draft was written to, stamped ONCE on the run.
        // Narrowed to the guides the AUTHOR SELECTED, matching the drafting
        // read one line down in `document_builder`: a guide they did not choose
        // is a rule about another document. Stored, never shown, and read by
        // nothing — the builder's adapter maps only the inputs it declares.
        rule_set_versions: (
          await currentRuleSetVersionIds(deps.db, slice.projectId, computed.body.styleGuideIds)
        ).join(','),
      });
    } catch (error) {
      if (!(error instanceof WorkflowNotRunnable)) throw error;
      return invalid(c, error.message);
    }

    // A tool run is a run, so it gets a Conversation like any other — the
    // Run/Step tree has one shape (ADR-0028 §1) and a second one for tools
    // would be a second audit story.
    const conversation = await createConversation(deps.db, {
      projectId: slice.projectId,
      surface: 'web',
    });

    // the set assembled for THIS requester (T-269), which is what the executor
    // resolves the step's named capability through
    const workers =
      deps.workers?.assemble({
        slice,
        tier: 'standard',
        authorityShelf: (await deps.authorityShelf?.(slice.organisationId)) ?? false,
      }) ?? [];

    let run: Run | null;
    let output: Record<string, unknown>;
    try {
      const executed = await runChain(deps.db, deps.leaves, {
        conversationId: conversation.id as Id,
        request: computed.body.brief,
        environmentKey: slice.projectId,
        requesterParticipantId: slice.participantId,
        workflow: {
          id: bound.workflowId,
          version: bound.workflowVersion,
          writes: bound.writes,
          ...(bound.labelPropagation !== undefined && { labelPropagation: bound.labelPropagation }),
        },
        stages: bound.stages,
        ...(deps.capabilities !== undefined && { capabilities: deps.capabilities }),
        entitledCapabilities: workers.map((worker) => worker.name),
        mode: 'declared',
      });
      run = await readRun(deps.db, executed.run.id);
      output = (executed.outputs['build'] as Record<string, unknown>) ?? {};
    } catch (error) {
      if (error instanceof CapabilityRefused) {
        // the entitlement refusal reads as nonexistence, exactly as every other
        // unreachable thing does (principle 4)
        return error.reason === 'not_entitled' ? notFound(c) : invalid(c, error.message);
      }
      throw error;
    }

    const manifest = (output['manifest'] as Array<{ versionId: Id; usedFor: string }>) ?? [];
    // T-402, moved to its right home by T-407. The `unsectioned` bucket is NOT
    // a section — the assembly writes the outline's own sections and nothing
    // else, so counting the bucket reported a section written into a document
    // that had none. The count is now taken **by the builder**, beside the
    // assembly that decides it, rather than derived here from the manifest's
    // headings: two sections of one author-composed outline may honestly share
    // a heading, and a count off those names would under-report, which is the
    // same class of error the other way round.
    const sectionsWritten = (output['sectionsWritten'] as number | undefined) ?? 0;
    const label = (output['label'] as {
      computedLabel: string;
      destinationLabel: string;
      refusal?: string;
    }) ?? { computedLabel: 'unknown', destinationLabel: 'unknown' };
    const withheld = (output['withheld'] as string[]) ?? [];
    const unreachableSources = (output['unreachableSources'] as Id[]) ?? [];

    return c.json(
      {
        run: run!,
        plan: computed.plan,
        // ADR-0053 §5's second statement, in the SAME SHAPE as the first: a
        // reader comparing the two sentences sees the difference at a glance,
        // which is what makes "4 bound sources" becoming "2 sources used" a
        // fact rather than something they have to go looking for.
        coverage: coverageAfter({
          sectionsWritten,
          // T-412 — the FLATTENED count, matching the plan's own sentence. The
          // two coverage statements are compared side by side by whoever reads
          // them (ADR-0053 §5), so a "4 of 2 sections written" would be the
          // after-sentence contradicting the before-sentence about the same
          // outline.
          sectionsPlanned: flattenOutline(computed.body.sections).length,
          sourcesUsed: new Set(manifest.map((entry) => entry.versionId)).size,
          sourcesBound: computed.body.sourceVersionIds.length,
          unreachableSources: unreachableSources.length,
          withheld: withheld.length,
          outsideOutline: (output['outsideOutline'] as number | undefined) ?? 0,
        }),
        documentId: (output['documentId'] as Id | null) ?? null,
        manifest: manifest.map((entry) => ({ versionId: entry.versionId, usedFor: entry.usedFor })),
        label: {
          computed: label.computedLabel,
          destination: label.destinationLabel,
          refusal: label.refusal ?? null,
        },
        withheld,
        unreachableSources,
      } satisfies DocumentCreationRunResponse,
      201,
    );
  });

  return app;
}
