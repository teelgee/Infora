-- ── `app_rows.state` is null EXACTLY when the table has no acceptance step ──
--
-- A trigger rather than a CHECK, because the fact lives one table away: the
-- builder's per-table choice (`app_tables.has_acceptance`, ADR-0056 §2a) is
-- what decides whether these rows ever change hands, and a CHECK cannot read
-- another table. Getting this wrong in either direction is a real failure: a
-- stateless row on a contractual table is a figure nobody ever accepted, and a
-- `draft` state on a table with no acceptance step is a submission flow nobody
-- asked for, silently hiding rows from the project owner.
CREATE OR REPLACE FUNCTION app_rows_state_matches_table() RETURNS trigger AS $$
DECLARE
  accepts boolean;
BEGIN
  SELECT has_acceptance INTO accepts FROM app_tables WHERE id = NEW.app_table_id;
  IF accepts IS NULL THEN
    RAISE EXCEPTION 'app row % names a table that does not exist', NEW.app_table_id;
  END IF;
  IF accepts AND NEW.state IS NULL THEN
    RAISE EXCEPTION 'app table % has an acceptance step: a row must carry a state', NEW.app_table_id;
  END IF;
  IF NOT accepts AND NEW.state IS NOT NULL THEN
    RAISE EXCEPTION 'app table % has no acceptance step: a row must carry no state', NEW.app_table_id;
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;--> statement-breakpoint

CREATE TRIGGER app_rows_state_matches_table
  BEFORE INSERT OR UPDATE ON app_rows
  FOR EACH ROW EXECUTE FUNCTION app_rows_state_matches_table();--> statement-breakpoint

-- ── AN ACCEPTED ROW IS NEVER EDITED OR DELETED IN PLACE (ADR-0056 §2a) ──────
--
-- This is the one the whole acceptance design rests on. On acceptance the row
-- becomes the project owner's record, retained exactly as accepted review-cycle
-- metadata is retained (ADR-0050 §8). If an accepted figure could be rewritten
-- afterwards, "accepted" would mean nothing: a payment trigger or a discharged
-- planning condition would rest on a number the submitting side could still
-- move. A correction is therefore a NEW row that supersedes the old one.
--
-- ONE TRANSITION IS PERMITTED, and it is the currency-by-state carve-out
-- migration 0013 made for `versions`: an accepted row may flip to `superseded`
-- when its correction arrives, and nothing else about it may move — not its
-- values, not its stamp, not its decider, not its reason. DELETE never.
CREATE OR REPLACE FUNCTION app_rows_accepted_is_frozen() RETURNS trigger AS $$
BEGIN
  IF TG_OP = 'DELETE' THEN
    IF OLD.state = 'accepted' THEN
      RAISE EXCEPTION 'app row % is accepted: it is the project owner''s record and is never deleted', OLD.id;
    END IF;
    RETURN OLD;
  END IF;
  IF OLD.state IS DISTINCT FROM 'accepted' THEN
    RETURN NEW;
  END IF;
  IF NEW.state IS DISTINCT FROM 'superseded' THEN
    RAISE EXCEPTION 'app row % is accepted: only a correction superseding it may change it', OLD.id;
  END IF;
  IF NEW.id IS DISTINCT FROM OLD.id
     OR NEW.app_table_id IS DISTINCT FROM OLD.app_table_id
     OR NEW.values IS DISTINCT FROM OLD.values
     OR NEW.organisation_id IS DISTINCT FROM OLD.organisation_id
     OR NEW.entered_by_participant_id IS DISTINCT FROM OLD.entered_by_participant_id
     OR NEW.entered_at IS DISTINCT FROM OLD.entered_at
     OR NEW.decided_by_participant_id IS DISTINCT FROM OLD.decided_by_participant_id
     OR NEW.decided_at IS DISTINCT FROM OLD.decided_at
     OR NEW.supersedes_row_id IS DISTINCT FROM OLD.supersedes_row_id
     OR NEW.previous_version_id IS DISTINCT FROM OLD.previous_version_id
     OR NEW.retired_at IS DISTINCT FROM OLD.retired_at
  THEN
    RAISE EXCEPTION 'app row % is accepted: its content and its stamp are frozen', OLD.id;
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;--> statement-breakpoint

CREATE TRIGGER app_rows_accepted_is_frozen
  BEFORE UPDATE OR DELETE ON app_rows
  FOR EACH ROW EXECUTE FUNCTION app_rows_accepted_is_frozen();--> statement-breakpoint

-- ── The two grant tables are append-only intervals ──────────────────────────
--
-- Scope grants and table shares are the wall's own audit trail, exactly as
-- `sandbox_scope_grants` and `deliverable_shares` are. Widening adds a row;
-- narrowing closes one. A grant that could be edited after the fact would make
-- "who could see this, and when" an assertion rather than a property — and a
-- revocation that could be reopened by an UPDATE would make revoking reversible
-- without a trace, which is the opposite of what revoking is for.
--
-- The comparison is over `to_jsonb(row) - the two revocation columns` so one
-- function serves both tables without listing either one's columns: a column
-- added later is frozen by default, which is the safe direction to be wrong in.
CREATE OR REPLACE FUNCTION app_grant_interval_only() RETURNS trigger AS $$
BEGIN
  IF TG_OP = 'DELETE' THEN
    RAISE EXCEPTION '% is an append-only interval: DELETE rejected', TG_TABLE_NAME;
  END IF;
  IF (to_jsonb(NEW) - 'revoked_at' - 'revoked_by_participant_id')
     IS DISTINCT FROM (to_jsonb(OLD) - 'revoked_at' - 'revoked_by_participant_id')
  THEN
    RAISE EXCEPTION '% row % is an interval: only its revocation may change', TG_TABLE_NAME, OLD.id;
  END IF;
  IF OLD.revoked_at IS NOT NULL AND NEW.revoked_at IS DISTINCT FROM OLD.revoked_at THEN
    RAISE EXCEPTION '% row % is already revoked: a revocation is never reopened', TG_TABLE_NAME, OLD.id;
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;--> statement-breakpoint

CREATE TRIGGER app_scope_grants_interval
  BEFORE UPDATE OR DELETE ON app_scope_grants
  FOR EACH ROW EXECUTE FUNCTION app_grant_interval_only();--> statement-breakpoint

CREATE TRIGGER app_table_shares_interval
  BEFORE UPDATE OR DELETE ON app_table_shares
  FOR EACH ROW EXECUTE FUNCTION app_grant_interval_only();--> statement-breakpoint

-- ── `app_runs` — two actor stamps, one truth ────────────────────────────────
--
-- The Drawer 3 `runs` row's own requester attribution is authoritative;
-- `as_participant_id` exists so app-side reads never have to join into Drawer 3,
-- and it must equal it. This matters more here than anywhere else in the
-- platform: a scheduled run acts as the APP'S OWNER (ADR-0056 §5), so every row
-- it writes and every insight it produces is attributed to that person. Two
-- stamps that could disagree would let the app-side record name one person
-- while the audit record named another, and there would be no way to tell which
-- was the lie.
--
-- The drawing calls it a CHECK; it is a trigger because it reads another table,
-- which is the one thing a CHECK constraint cannot do.
CREATE OR REPLACE FUNCTION app_runs_actor_agrees() RETURNS trigger AS $$
DECLARE
  requester uuid;
BEGIN
  SELECT requester_participant_id INTO requester FROM runs WHERE id = NEW.run_id;
  IF requester IS NULL THEN
    RAISE EXCEPTION 'app run names run % which does not exist', NEW.run_id;
  END IF;
  IF requester IS DISTINCT FROM NEW.as_participant_id THEN
    RAISE EXCEPTION 'app run acts as % but run % was requested by %: the two stamps must agree',
      NEW.as_participant_id, NEW.run_id, requester;
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;--> statement-breakpoint

CREATE TRIGGER app_runs_actor_agrees
  BEFORE INSERT OR UPDATE ON app_runs
  FOR EACH ROW EXECUTE FUNCTION app_runs_actor_agrees();--> statement-breakpoint

-- Append-only, immutable once finished — the T-008 pattern for a two-phase row,
-- the same shape `runs` itself carries. What a run DID is evidence; only its
-- completion may be written after the fact.
CREATE OR REPLACE FUNCTION app_runs_immutable_once_finished() RETURNS trigger AS $$
BEGIN
  IF TG_OP = 'DELETE' THEN
    RAISE EXCEPTION 'app_runs are append-only: DELETE rejected';
  END IF;
  IF OLD.finished_at IS NOT NULL THEN
    RAISE EXCEPTION 'app run % is finished and immutable', OLD.id;
  END IF;
  IF NEW.id IS DISTINCT FROM OLD.id
     OR NEW.app_id IS DISTINCT FROM OLD.app_id
     OR NEW.run_id IS DISTINCT FROM OLD.run_id
     OR NEW.trigger IS DISTINCT FROM OLD.trigger
     OR NEW.as_participant_id IS DISTINCT FROM OLD.as_participant_id
     OR NEW.definitions_version IS DISTINCT FROM OLD.definitions_version
     OR NEW.started_at IS DISTINCT FROM OLD.started_at
  THEN
    RAISE EXCEPTION 'app run % identity is immutable: only its outcome may be written', OLD.id;
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;--> statement-breakpoint

CREATE TRIGGER app_runs_append_only
  BEFORE UPDATE OR DELETE ON app_runs
  FOR EACH ROW EXECUTE FUNCTION app_runs_immutable_once_finished();--> statement-breakpoint

