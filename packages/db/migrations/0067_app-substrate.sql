-- ── `apps` — two pair CHECKs ────────────────────────────────────────────────
--
-- ALL FOUR PUBLISHED COLUMNS MOVE TOGETHER (ADR-0056's 2026-09-06 addendum,
-- ruling 2). An app has a working copy of its definition and a published one;
-- the builder edits the working copy, the app's people open the published one,
-- and a scheduled run acts only against the published one. "Publishing" is one
-- act — copy, version, stamp who, stamp when — so a row carrying three of the
-- four would be an app that is somehow published by nobody, or at no time, or
-- with no content. `num_nonnulls` counts FOUR: the drawing's own bullet once
-- said three over a list of four, and the count was corrected in review.
ALTER TABLE "apps" ADD CONSTRAINT "apps_published_quartet"
  CHECK (num_nonnulls("published_definition", "published_version", "published_by_participant_id", "published_at") IN (0, 4));--> statement-breakpoint

