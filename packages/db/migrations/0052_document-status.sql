-- Hand-added backfill: existing schemes keep the behaviour they already had.
-- Before this migration, acceptance WAS admission and admission WAS grounding —
-- an accepted deliverable entered the library and grounded, with no third
-- condition. Defaulting existing rows to `false` would silently stop every
-- already-accepted deliverable in an existing project from grounding; setting
-- them from `is_accepting` reproduces the pre-migration rule exactly, which is
-- the honest reading of history for data written under it. New schemes take the
-- 2021 National Annex defaults from the seed, not from here.
UPDATE "acceptance_codes"
   SET "is_contractual" = "is_accepting",
       "grounds" = "is_accepting";
