-- the starting intervals, for every project that already exists: the four
-- document types reference material takes (found by label in the project's
-- own document_type facet, live terms only) and the project-wide fallback.
INSERT INTO "recheck_defaults" ("project_id", "term_id", "interval_months")
SELECT f."project_id", t."id", v."months"
FROM "classification_facets" f
JOIN "classification_terms" t ON t."facet_id" = f."id" AND t."retired_at" IS NULL
JOIN (VALUES
  ('standard', 12),
  ('guidance', 12),
  ('legislation', 6),
  ('consultee response', 24)
) AS v("label", "months") ON lower(t."label") = v."label"
WHERE f."key" = 'document_type'
ON CONFLICT DO NOTHING;
